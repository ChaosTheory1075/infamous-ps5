#!/usr/bin/env python3
# Writes runtime/spu/spu_tables.h: pshufb controls for spu__xb_rot/shl/shr and the cbd/chd/cwd/cdd
# insertion masks, one row per position/shift, computed exactly as the reference byte loops build them
# (SPU byte P lives at host byte P^3). Checked against the old forms for every input (2026-11-05).
#   gen_spu_tables.py [~/if2/ps3recomp-fork/runtime/spu/spu_tables.h]
import sys
W = lambda p: p ^ 3
def base():
    r = [0]*16
    for t in range(16): r[W(t)] = 0x10 + t
    return r
def cbd(pos): r = base(); r[W(pos & 15)] = 3; return r
def chd(pos): r = base(); p = (pos & 15) & ~1; r[W(p)] = 2; r[W(p+1)] = 3; return r
def cwd(pos):
    r = base(); p = (pos & 15) & ~3
    for k in range(4): r[W(p+k)] = k
    return r
def cdd(pos):
    r = base(); p = (pos & 15) & ~7
    for k in range(8): r[W(p+k)] = k
    return r
def rot(sh): return [((((h ^ 3) + sh) & 15) ^ 3) for h in range(16)]
def shl(sh): return [0x80 if (h ^ 3) + sh > 15 else (((h ^ 3) + sh) ^ 3) for h in range(16)]
def shr(sh): return [0x80 if (h ^ 3) - sh < 0 else (((h ^ 3) - sh) ^ 3) for h in range(16)]
def tab(name, f, n):
    rows = ",\n".join("    {" + ",".join("0x%02X" % b for b in f(i)) + "}" for i in range(n))
    return "static const uint8_t %s[%d][16] __attribute__((aligned(16))) = {\n%s\n};\n" % (name, n, rows)
h = "/* Generated by tools/gen_spu_tables.py: lookup tables for the x86 SPU helpers (spu_helpers.h).\n * Each row is exactly what the byte-loop reference form builds for that position / shift. */\n#pragma once\n#include <stdint.h>\n"
h += tab("spu_t_cbd", cbd, 16) + tab("spu_t_chd", chd, 16) + tab("spu_t_cwd", cwd, 16) + tab("spu_t_cdd", cdd, 16)
h += tab("spu_t_rot", rot, 16) + tab("spu_t_shl", shl, 32) + tab("spu_t_shr", shr, 32)
open(sys.argv[1] if len(sys.argv) > 1 else __import__("os").path.expanduser("~") + "/if2/ps3recomp-fork/runtime/spu/spu_tables.h", "w").write(h)
