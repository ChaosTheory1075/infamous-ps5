#!/usr/bin/env python3
"""lift_if1_plugmods.py EBOOT.elf --out <port>/spu [--first-image-id 330] [--extra 0xEA:0xOFF,..]

inFAMOUS 1's twelve small WWS job modules at EBOOT 0x670100-0x684100 (4 x ila signature, then
words size_a, total, 0, 0x40, c, d, 0, 1; code from +0x30). Job 209 copies them into its own
local-store buffer wherever there is room and calls into them, so no fixed-address lift fits.
Each is lifted at LS 0 (header included, so offsets are from the module start) with the
toolkit's SPU lifter in --relocatable mode, and <out>/relocmods_register.c registers it by
content with spu_overlay_register_reloc_sig (tools/patch_spu_reloc_sig.py): dispatch adopts the
lift wherever the module's bytes sit. PS3_RELOCMODS=0 leaves them to the interpreter.
"""
import argparse, os, re, struct, subprocess, sys

TOOLKIT = os.environ.get('PS3RECOMP', __import__("os").path.expanduser("~") + '/if2/ps3recomp-fork')
sys.path.insert(0, os.path.join(TOOLKIT, 'tools'))
import lift_jobmods as lj          # noqa: E402
from wrap_spu_elf import wrap      # noqa: E402
INC_RE = re.compile(r'#include "(?:\.\./)+runtime/spu/')


def find_modules(d, lo=0, hi=None):
    out = []
    for o in range(lo, (hi or len(d)) - 48, 16):
        w = struct.unpack_from('>12I', d, o)
        if all((w[k] >> 24) in (0x42, 0x43) for k in range(4)) and w[6] == 0 and w[7] == 0x40 \
                and 0 < w[4] <= w[5] < 0x40000 and w[11] == 1:
            out.append((o, w[4], w[5]))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('eboot'); ap.add_argument('--out', required=True)
    ap.add_argument('--first-image-id', type=int, default=330)
    ap.add_argument('--va-offset', type=lambda x: int(x, 0), default=0x10000)
    ap.add_argument('--extra', default='', help='"0xEA:0xOFF" entries (offsets from the module start)')
    a = ap.parse_args()
    d = open(a.eboot, 'rb').read()
    mods = find_modules(d)
    extra = {}
    for tok in filter(None, (t.strip() for t in a.extra.split(','))):
        ea, off = (int(x, 0) for x in tok.split(':')); extra.setdefault(ea, set()).add(off)
    regs = []
    for n, (s, code_len, span) in enumerate(mods):
        ea = s + a.va_offset; raw = d[s:s + span]
        name = f'plugmod_{ea:08x}'; prefix = name + '_'
        outsub = os.path.join(a.out, name); os.makedirs(outsub, exist_ok=True)
        tmp = os.path.join(a.out, f'_tmp_{name}.elf')
        open(tmp, 'wb').write(wrap(raw, base=0, entry=0x30))
        extras = {'0x30'}
        extras |= {hex(x) for x in lj.manual_link_targets(raw, base=0) if 0x30 <= x < span}
        extras |= {hex(x) for x in lj.switch_table_targets(raw, base=0) if 0x30 <= x < span}
        extras |= {hex(x) for x in extra.get(ea, ())}
        cmd = [sys.executable, os.path.join(TOOLKIT, 'tools', 'spu_lifter.py'), '--auto-functions', tmp,
               '--base', '0', '--relocatable', '--symbol-prefix', prefix, '-o', outsub,
               '--source-name', 'spu_recomp.c', '--header-name', 'spu_recomp.h',
               '--code-end', hex(span), '--extra-funcs', ','.join(sorted(extras, key=lambda x: int(x, 16)))]
        r = subprocess.run(cmd, capture_output=True, text=True); os.remove(tmp)
        if r.returncode != 0:
            sys.exit(f'{name}: lift failed\n{r.stderr[-3000:]}')
        for fn in ('spu_recomp.c', 'spu_recomp.h'):
            p = os.path.join(outsub, fn); t = open(p).read(); open(p, 'w').write(INC_RE.sub('#include "', t))
        funcs = next((l.strip() for l in r.stdout.splitlines() if l.strip().endswith('function(s) lifted')), '?')
        img = a.first_image_id + n
        print(f'  {name}: code 0x{code_len:X} span 0x{span:X} -> image {img}, {funcs}')
        regs.append((name, prefix, ea, span, code_len, img, raw[0x30:0x40]))
    L = ['/* relocmods_register.c -- GENERATED by tools/lift_if1_plugmods.py (inFAMOUS 1 job-209 modules).',
         ' * Lifted at LS 0 --relocatable; registered by content (spu_overlay_register_reloc_sig): dispatch',
         ' * adopts the lift wherever job 209 copied the module. */',
         '#include <stdint.h>', '',
         'extern void spu_begin_image(int image_id);',
         'extern void spu_overlay_register_reloc_sig(const uint8_t sig[16], uint32_t sig_off, uint32_t content_ea, uint32_t span, uint32_t code_len, int image_id);']
    L += [f'extern void {p}spu_recomp_register(void);' for _, p, *_ in regs]
    L += ['', '__attribute__((constructor)) static void infamous_plugmods_register(void)', '{',
          '    /* PS3_RELOCMODS=0 leaves them to the interpreter (A/B comparisons). */',
          '    { extern char* getenv(const char*); const char* e = getenv("PS3_RELOCMODS");',
          "      if (e && e[0] == '0') return; }"]
    for name, p, ea, span, code_len, img, sig in regs:
        L.append(f'    {{ static const uint8_t sig[16] = {{{",".join("0x%02X" % b for b in sig)}}};')
        L.append(f'      spu_begin_image({img}); {p}spu_recomp_register();')
        L.append(f'      spu_overlay_register_reloc_sig(sig, 0x30u, 0x{ea:08X}u, 0x{span:X}u, 0x{code_len:X}u, {img}); }}   /* {name} */')
    L += ['    spu_begin_image(0);', '}', '']
    open(os.path.join(a.out, 'relocmods_register.c'), 'w').write('\n'.join(L))
    print(f'wrote relocmods_register.c ({len(regs)} modules)')


if __name__ == '__main__':
    main()
