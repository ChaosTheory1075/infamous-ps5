# Generate cheat_table_if2.inc (DATA-only inFAMOUS 2 NPUA80638 cheats/patches) from the parsed CT + fixed patch list.
# Usage: python3 -I gen_inc.py "<Unlock Powers (inF2).CT>" "<rpcs3.CT>" out.inc
import sys, struct, xml.etree.ElementTree as ET, re
RPCS3_BASE = 0x300000000

def entries(path):
    out = []
    def walk(e, grp):
        for ce in e.findall('CheatEntries/CheatEntry'):
            d = (ce.findtext('Description') or '').strip().strip('"')
            a = (ce.findtext('Address') or '').strip()
            t = (ce.findtext('VariableType') or '') + ':' + (ce.findtext('CustomType') or '')
            if a: out.append((grp, d, int(a, 16) - RPCS3_BASE, t))
            walk(ce, d if not a else grp)
    walk(ET.parse(path).getroot(), '')
    return out

def script_enable_values(path):
    for ce in ET.parse(path).getroot().iter('CheatEntry'):
        s = ce.findtext('AssemblerScript')
        if s:
            body = s.split('{$lua}', 1)[1]
            first = body.split('local newState', 1)[0]          # the first config table (the ENABLE one)
            return dict(re.findall(r'name = "([^"]+)",\s*val = "(\d+)"', first))
    return {}

up, rp, outp = sys.argv[1:4]
E = entries(up); vals = script_enable_values(up)
f32 = lambda x: struct.unpack('>I', struct.pack('>f', x))[0]
L = []
L.append('/* cheat_table_if2.inc -- PROTOTYPE, generated by tools/gpatch/gen_cheat_table.py (not used by any build).')
L.append(' * inFAMOUS 2 NPUA80638 01.03, RPCS3 key PPU-41a7d047c573c78c0307506c9d1b52d15a66e4f5 (the port\'s EBOOT).')
L.append(' * DATA-only cheats/patches: every entry is a write to guest memory (vm_base + ea, big-endian), no code change.')
L.append(' *   expect: the value the EBOOT/boot state must hold before a ONCE write to an ELF constant (CW_ANY: runtime state).')
L.append(' *   apply : CA_ONCE at boot after the ELF is loaded (ELF constants) / CA_FREEZE every frame (game state the game')
L.append(' *           keeps rewriting) / CA_SET once when toggled on in the menu (save-state values: progress is kept by the save).')
L.append(' * Cheat Engine addresses were RPCS3 host addresses: guest ea = host - 0x300000000. Untested on the port. */')
L.append('#pragma once')
L.append('#include <stdint.h>')
L.append('enum { CW_U8 = 1, CW_BE16 = 2, CW_BE32 = 4 };          /* write width; floats are CW_BE32 bit patterns */')
L.append('enum { CA_ONCE, CA_SET, CA_FREEZE };')
L.append('#define CW_ANY 0xFFFFFFFFu')
L.append('typedef struct { uint32_t ea; uint8_t width; uint32_t expect, value; } cheat_write;')
L.append('typedef struct { const char* id; const char* name; const char* credit; uint8_t apply; uint16_t n; const cheat_write* w; } cheat_def;')
L.append('#define CHEAT_IF2_PPU_HASH "41a7d047c573c78c0307506c9d1b52d15a66e4f5"')
L.append('')
defs = []
def add(id_, name, credit, apply, writes, comment=''):
    if comment: L.append('/* %s */' % comment)
    L.append('static const cheat_write k_if2_%s[] = {' % id_)
    for ea, wd, ex, v, c in writes:
        L.append('    { 0x%08Xu, %s, %s, 0x%08Xu },%s' % (ea, {1: 'CW_U8', 2: 'CW_BE16', 4: 'CW_BE32'}[wd],
                 'CW_ANY' if ex is None else '0x%08Xu' % ex, v, ('   /* %s */' % c) if c else ''))
    L.append('};')
    defs.append((id_, name, credit, apply, len(writes)))

# RPCS3 patch.yml (official) entries for this EBOOT: data words
add('skip_intro', 'Skip Intro', 'FlexBy (RPCS3 patch.yml)', 'CA_ONCE', [(0x007CDBA8, 4, 0x73706C61, 0, 'first word of the splash movie name ("spla...")')])
add('ext_fov', 'Extended FOV', 'illusion (RPCS3 patch.yml)', 'CA_ONCE', [(0x0096DE14, 4, 0x00000004, f32(0.65), 'bef32 0.65')])
add('mesh_trim', 'Disable Mesh Trimming', 'Yahfz (RPCS3 patch.yml)', 'CA_ONCE', [(0x008875C0, 4, 0x21000984, 0x4020007F, 'table word')])
# L_'s Static Thrusters - Fast as data: the getter's pool float, shared with 10 other thruster getters (approximation)
add('thrusters_fast', 'Static Thrusters - Fast (data approximation)', 'L_ (imported_patch.yml)', 'CA_ONCE',
    [(0x009A4E88, 4, f32(1350.0), f32(2000.0), 'pool float 1350.0 -> 2000.0; read by func_0019B274 and 10 sibling getters')],
    'Exact version = native hook at 0x0019B2EC (see CHEATS_FEASIBILITY.md).')
# Cheat tables (rpcs3.CT, "Unlock Powers (inF2).CT"): progress block at 0x00A64E20 (TOC-referenced)
add('karma_good', 'Karma: max Good', 'rpcs3.CT', 'CA_SET', [(0x00A64E40, 4, None, f32(3200.0), 'float BE')])
add('karma_evil', 'Karma: max Evil', 'rpcs3.CT', 'CA_SET', [(0x00A64E40, 4, None, f32(-3200.0), 'float BE')])
add('ionic3', 'Ionic charges: 3', 'Unlock Powers (inF2).CT', 'CA_FREEZE', [(0x00A64E5A, 2, None, 3, 'u16 BE 0..3')])
add('hide_hud', 'Hide HUD', 'rpcs3.CT', 'CA_FREEZE', [(0x00A7631B, 1, None, 1, 'byte 1 = hidden')])
# Unlock All Powers: the CT's Lua script sets each record of the "Unlock Power Upgrades" / "Blast Core Upgrades" folders
ups = []
for grp, d, ea, t in E:
    if d in vals and grp not in ('Power Selecter',) and not (d == 'Ionic Charges'):
        v = int(vals[d])
        if t.startswith('2 Bytes') and ea & 1:      # CE little-endian 2-byte at an odd address = the field's low byte
            ups.append((ea, 1, None, v & 0xFF, '%s (%s)' % (d, grp)))
        else:
            ups.append((ea & ~1 if t.startswith('2 Bytes') else ea, 2, None, v, '%s (%s)' % (d, grp)))
add('unlock_all', 'Unlock all powers + upgrades', 'Unlock Powers (inF2).CT script', 'CA_SET', ups,
    'Values as the CT script\'s enable list (95 = upgrades, 120 = blast-core "perma unlocked"); the dropdowns say 7 = unlocked, 39 = unlocked.\n * Unlocks are written into the save when it is next saved (permanent), as the Ability Manager README warns.')
L.append('')
L.append('static const cheat_def k_cheats_if2[] = {')
for id_, name, credit, apply, n in defs:
    L.append('    { "%s", "%s", "%s", %s, %d, k_if2_%s },' % (id_, name, credit, apply, n, id_))
L.append('};')
L.append('')
L.append('/* Not data-only, so not in this table (native hooks, need a game-program rebuild): Static Thrusters - Flight (hook')
L.append(' * 0x0019B388; or a per-frame tick that repoints pool slot 0x009A4E94 from 0x007C1370 to a spare 16-byte slot and writes')
L.append(' * {5.5|600|-1200} there from the pad), Black Lightning (call 0x002CFA3C), Expand pack buffer (0x000DD900..08 immediates),')
L.append(' * Cole Never Dies (0x0017AC50..58), karma / jump / AI-speed / electricity patches (1-4 instructions each). */')
open(outp, 'w').write('\n'.join(L) + '\n')
print(len(defs), 'cheats,', len(ups), 'unlock writes')
