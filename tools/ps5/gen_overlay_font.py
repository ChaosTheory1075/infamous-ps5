# gen_overlay_font.py: the frame-rate overlay's glyphs (DejaVu Sans Bold / Book, the sizes GTA IV's counter uses at
# s = 2, i.e. 4K) as 8-bit alpha bitmaps in a C header for libs/video/vk_overlay.c.
import sys
from PIL import Image, ImageFont, ImageDraw
BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"; BODY = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
ASCII = "".join(chr(c) for c in range(32, 127)) + "·"
FONTS = [("big", BOLD, 72, "0123456789-"), ("ms", BOLD, 40, "0123456789. ms"), ("unit", BOLD, 30, "FPS"),
         ("mark", BOLD, 22, "0123456789"), ("body", BODY, 28, ASCII)]
out = ["/* generated by tools/ps5/gen_overlay_font.py -- do not edit */", "#include <stdint.h>",
       "typedef struct { uint16_t cp, w, h, off; int16_t bx, by, adv; } vk_ovl_glyph;",
       "typedef struct { const char* name; int px, ascent, descent; int n; const vk_ovl_glyph* g; const uint8_t* bits; } vk_ovl_font;"]
for name, path, px, chars in FONTS:
    f = ImageFont.truetype(path, px); asc, desc = f.getmetrics()
    glyphs, bits = [], bytearray()
    for ch in chars:
        l, t, r, b = f.getbbox(ch, anchor="ls")  # baseline-left anchor
        w, h = max(r - l, 0), max(b - t, 0)
        im = Image.new("L", (w + 2, h + 2), 0)
        ImageDraw.Draw(im).text((-l + 1, -t + 1), ch, font=f, fill=255, anchor="ls")
        adv = f.getlength(ch)
        glyphs.append((ord(ch), w + 2, h + 2, len(bits), l - 1, t - 1, round(adv)))
        bits += im.tobytes()
    out.append("static const vk_ovl_glyph s_ovl_%s_g[%d] = {" % (name, len(glyphs)))
    out += ["    { %d, %d, %d, %d, %d, %d, %d }," % g for g in glyphs]
    out.append("};")
    out.append("static const uint8_t s_ovl_%s_bits[%d] = {" % (name, len(bits)))
    for i in range(0, len(bits), 32): out.append("    " + ",".join(str(x) for x in bits[i:i + 32]) + ",")
    out.append("};")
    out.append("static const vk_ovl_font s_ovl_%s = { \"%s\", %d, %d, %d, %d, s_ovl_%s_g, s_ovl_%s_bits };" % (name, name, px, asc, desc, len(glyphs), name, name))
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print("wrote", sys.argv[1])
