#!/usr/bin/env python3
"""gen_inc.py <eboot.udp> <out .inc>: the UDP1 patch (USA inFAMOUS EBOOT.elf -> Europe EBOOT.elf) as a C array."""
import sys, hashlib
d = open(sys.argv[1], "rb").read()
assert d[:4] == b"UDP1"
o = ["/* Generated by tools/ps5/launcher/if1_usa/gen_inc.py from eboot.udp (%d bytes, sha256 %s).\n"
     " * UDP1 patch: the decrypted USA inFAMOUS EBOOT.elf (BCUS98119 v01.00/v02.00, sha256 4f2db3fb..) -> the Europe one\n"
     " * (BCES00220, sha256 095d8514..) the build was made from. Applied by inst_udp1() in installer.c. */\n" % (len(d), hashlib.sha256(d).hexdigest()),
     "static const unsigned char kIf1UsaEbootPatch[%d] = {\n" % len(d)]
for i in range(0, len(d), 32):
    o.append("".join("%d," % b for b in d[i:i+32]) + "\n")
o.append("};\n")
open(sys.argv[2], "w").write("".join(o))
